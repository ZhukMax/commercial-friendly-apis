#!/usr/bin/env python3
"""Generate review-needed.md: second-check disagreements and open questions for the maintainer."""
import yaml, glob, datetime, json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
E = sorted((yaml.safe_load(open(f)) for f in glob.glob(str(ROOT / "data/apis/*.yaml"))), key=lambda e: e["id"])
ICON = {"green": "🟢", "yellow": "🟡", "red": "🔴", "unknown": "⚪"}
L = ["# Review needed (generated by scripts/review_needed.py)", "", f"Updated: {datetime.date.today()}", "",
     "First pass found terms; a second, adversarial pass looked for reasons the API cannot be used on a commercial site. "
     "Entries below are where the two passes disagree. The current verdict already reflects the more cautious reading.", "",
     "## Decisions already taken", "",
     "- Silence about caching no longer lowers an entry to ⚪: commercial use allowed but storage/display unconfirmed gives 🟡; 🟢 needs both confirmed.",
     "- Portal catalogues keep their verdict but carry ⚠️ (`license_scope: portal-default`): the licence is the portal default, datasets may differ.",
     "- APIs that are not data sources (payments, e-mail, self-hosted software, account-scoped, demos) carry `applicable: false` and are left out of tables and counters.",
     "- Duplicate entries of one service were merged (`aliases` lists the removed ids); the more cautious verdict was kept.",
     "- Data licence: CC BY 4.0 (see LICENSE-DATA).", "",
     "## Disputed by the second check", ""]
R = {}
for f in sorted(glob.glob(str(ROOT / "data/second_pass/result-*.json"))):
    for r in json.load(open(f)): R[r["id"]] = r
D = [e for e in E if e.get("second_check") == "disputed"]
L.append(f"{len(D)} entries.")
L.append("")
for e in D:
    L.append(f"### {ICON[e['verdict']]} {e['name']} (`{e['id']}`)")
    L.append(f"- {e['url']}")
    r = R.get(e["id"], {})
    L.append(f"- Reason: {'; '.join(r.get('reasons', [])) or e.get('second_check_note','')}")
    for x in r.get("counter_evidence", [])[:3]:
        L.append(f"- Counter-evidence ({x.get('field','')}): “{x['quote']}” — {x['url']}")
    L.append("")
(ROOT / "review-needed.md").write_text("\n".join(L), encoding="utf-8")
print(len(D), "disputed written")
