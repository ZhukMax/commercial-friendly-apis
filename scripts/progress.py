#!/usr/bin/env python3
"""Write progress.md: what is verified, what is left, problem cases."""
import yaml, glob, collections, datetime
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
E = [yaml.safe_load(open(f)) for f in glob.glob(str(ROOT / "data/apis/*.yaml"))]
PRIORITY = ["Government", "Open Data", "Geocoding", "Weather", "Environment", "Transportation", "Health",
            "Science & Math", "Finance", "Food & Drink", "Books", "Business"]
L = ["# Progress (generated by scripts/progress.py)", "", f"Updated: {datetime.date.today()}", "",
     "| Category | Total | Dead link | Checked | Left | 🟢 | 🟡 | 🔴 | ⚪ checked |", "|---|---|---|---|---|---|---|---|---|"]
cats = PRIORITY + sorted({e["category"] for e in E} - set(PRIORITY))
for c in cats:
    es = [e for e in E if e["category"] == c]
    if not es: continue
    dead = [e for e in es if e.get("link_status") == "dead"]
    ch = [e for e in es if e.get("checked_at")]
    left = [e for e in es if not e.get("checked_at") and e.get("link_status") != "dead"]
    v = collections.Counter(e["verdict"] for e in ch)
    L.append(f"| {c}{' ⭐' if c in PRIORITY else ''} | {len(es)} | {len(dead)} | {len(ch)} | {len(left)} | {v['green']} | {v['yellow']} | {v['red']} | {v['unknown']} |")
L += ["", "⭐ = priority category (checked first).", "", "## Problem cases (checked, verdict unknown or low confidence)", ""]
for e in sorted(E, key=lambda e: e["id"]):
    if e.get("checked_at") and (e["verdict"] == "unknown" or e.get("confidence") == "low"):
        L.append(f"- `{e['id']}` ({e['verdict']}, confidence {e['confidence']}): {e.get('notes','')[:200]}")
(ROOT / "progress.md").write_text("\n".join(L) + "\n")
print("progress.md written")
